"""FM-1 Again's faces: TeX Gyre Heros Bold (a free Helvetica, GUST Font License) as fm1-base fonts, plain and
"stamped": each glyph roughened at its edges and pitted with small square holes, as a rubber stamp or a photocopy
leaves a letter (the look of the stamped capitals on the USB002 posters, made anew here from the plain glyph).

  /usr/bin/python3 app/tools/gen_again_font.py      -> app/gen/again_font.h

The layout is fm1-base's untrimmed one (device/gfx.c felucca_font_t, tools/gen_font.py without FM1_FONT_TRIM):
each glyph its rows of 4-bit alphas, two to a byte, bitmap width bw starting PAD pixels left of the pen."""
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

APP = Path(__file__).resolve().parent.parent
TTF = APP / "assets/fonts/texgyreheros-bold.otf"
OUT = APP / "gen/again_font.h"
PAD = 1
OVER = 4                          # stamped glyphs are made at 4x and brought down

# name, pixel size, stamped, first, last
FACES = [("AG_T", 10, False, 32, 126),    # the pads' strip, the tabs
         ("AG_S", 13, False, 32, 126),    # the waveform's title bar
         ("AG_M", 20, False, 32, 126),    # second lines
         ("AG_L", 30, False, 32, 126),    # the big words and numbers
         ("AG_LS", 30, True, 32, 126)]    # the same, stamped


def stamp(img, seed):
    """img: L at OVER x size, the glyph white on black; returns it roughened and pitted"""
    rnd = random.Random(seed)
    w, h = img.size
    if not img.getbbox():
        return img
    # swollen and rounded, as ink spreads under a stamp: grown, blurred and cut again
    soft = img.filter(ImageFilter.MaxFilter(OVER + 1)).filter(ImageFilter.GaussianBlur(OVER * 0.6))
    # a ragged edge: a blurred noise field moves the cut in and out
    noise = Image.effect_noise((w, h), 160).filter(ImageFilter.GaussianBlur(OVER * 0.5))
    f, n = soft.load(), noise.load()
    out = Image.new("L", (w, h), 0)
    o = out.load()
    for y in range(h):
        for x in range(w):
            if f[x, y] + (n[x, y] - 128) * 0.8 > 128:
                o[x, y] = 255
    # speckle: fine dark grains inside
    for _ in range(w * h // 150):
        x, y = rnd.randrange(w), rnd.randrange(h)
        if o[x, y]:
            ImageDraw.Draw(out).rectangle([x, y, x + OVER // 2, y + OVER // 2], fill=0)
    # pits: small square holes, a few per glyph, about 2 px on the screen
    side = 2 * OVER
    for _ in range(max(3, (w * h) // (side * side * 45))):
        x, y = rnd.randrange(w - side), rnd.randrange(h - side)
        if o[x + side // 2, y + side // 2]:
            ImageDraw.Draw(out).rectangle([x, y, x + side - 1, y + side - 1], fill=0)
    return out


def render(px, stamped, first, last):
    plain = ImageFont.truetype(str(TTF), px)          # the metrics: the plain face's, so both share a baseline
    asc, desc = plain.getmetrics()
    top = max(0, plain.getbbox("A8|(")[1] - 1)
    h = asc + desc - top
    k = OVER if stamped else 1
    font = ImageFont.truetype(str(TTF), px * k)
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(plain.getlength(ch)))
        bw = adv + 2 * PAD
        img = Image.new("L", (bw * k, h * k), 0)
        ImageDraw.Draw(img).text((PAD * k, -top * k), ch, font=font, fill=255)
        if stamped:
            img = stamp(img, c * 7919 + px).resize((bw, h), Image.LANCZOS)
        a = [min(15, (v + 8) // 17) for v in img.tobytes()]
        glyphs.append((adv, bw, a))
    return h, glyphs


def main():
    lines = ["/* generated by app/tools/gen_again_font.py: TeX Gyre Heros Bold (GUST Font License), plain and stamped */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, px, stamped, first, last in FACES:
        h, glyphs = render(px, stamped, first, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536, name
        lines.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t {name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t {name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t {name}_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t {name} = {{ {h}, {PAD}, {first}, {last}, "
                     f"{name}_ADV, {name}_BW, {name}_OFF, {name}_DATA }};")
        lines.append("")
        print(f"{name}: {px}px{' stamped' if stamped else ''}, h {h}, {len(data)} B")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
