"""FM-1 Again's tables (app/gen/again_tables.h): the parts of Felucca's / Arctic Scream's tools/gen_tables.py that
its ported modules need: the soft clip's curve (dsp/qdsp.h softclip) and SPACE's line gains (dsp/space.h).

  /usr/bin/python3 app/tools/gen_tables.py"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "gen/again_tables.h"


def arr(name, typ, vals, per=16):
    L = [f"static const {typ} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        L.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return L + ["};"]


def main():
    L = ["/* generated by app/tools/gen_tables.py */", "#pragma once", "#include <stdint.h>", ""]
    # soft clip curve for |x| in 0..2 (Q12 in, Q15 out): tanh (Felucca's)
    L += arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    # SPACE (dsp/space.h, Arctic Scream's after Felucca's HALL): RT60 = 0.4 s * 2^(SIZE / 20) for SIZE 0..126,
    # 127 = INF. A line of D samples (22.05 kHz) loses 60 dB in RT60 * 22050 / D passes:
    # g = 10^(-3 D / (22050 RT60)), over sqrt(7) (the matrix's rows), Q14. INF: lossless but for 1e-4 a pass
    lens = [853, 941, 1031, 1123, 1237, 1361, 1493, 1637]
    rt = [0.4 * 2 ** (s / 20) for s in range(127)]
    g = [[int(round(16384 / math.sqrt(7) * min(0.999, 10 ** (-3 * d / (22050 * t))))) for d in lens] for t in rt]
    g.append([6192] * len(lens))
    L += [f"static const int16_t RV_G[128][{len(lens)}] = {{"]
    L += ["    {" + ", ".join(str(v) for v in row) + "}," for row in g]
    L += ["};"]
    L += arr("RV_RT60_X10", "uint16_t", [int(round(t * 10)) for t in rt])
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"tables: {OUT}")


if __name__ == "__main__":
    main()
